import { expect, test } from '@playwright/test'
import type { Locator } from '@playwright/test'

async function selectText(visual: Locator, text: string, start = 0, end = text.length) {
  await visual.evaluate((root, selected) => {
    const element = [...root.querySelectorAll('[data-source-start]')].find(node => node.textContent === selected.text)
    if (!element?.firstChild) throw new Error(`Missing editor text ${selected.text}`)
    ;(root as HTMLElement).focus()
    const range = document.createRange()
    range.setStart(element.firstChild, selected.start); range.setEnd(element.firstChild, selected.end)
    const selection = window.getSelection()!
    selection.removeAllRanges(); selection.addRange(range)
    document.dispatchEvent(new Event('selectionchange'))
  }, { text, start, end })
}

test('Visual tools toggle formatting, edit links safely, and resize tables without changing surrounding Markdown', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  const markdown = page.getByRole('textbox', { name: 'Markdown content', exact: true })
  const source = 'Before **bold** and [link](https://old.example/).\n\n| A | B |\n| :--- | ---: |\n| One | Two |\n\nAfter.'
  await markdown.fill(source)
  await page.getByRole('button', { name: 'Visual', exact: true }).click()
  const visual = page.getByRole('textbox', { name: 'Visual content', exact: true })
  await selectText(visual, 'bold')
  await expect(page.getByRole('button', { name: 'Bold', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('button', { name: 'Bold', exact: true }).click()
  await expect(visual.locator('strong')).toHaveCount(0)
  await visual.getByRole('link', { name: 'link' }).click()
  const dialog = page.getByRole('dialog', { name: 'Edit link', exact: true })
  await expect(dialog).toBeVisible()
  await dialog.getByRole('textbox', { name: 'Link URL' }).fill('javascript:alert(1)')
  await dialog.getByRole('button', { name: 'Save link' }).click()
  await expect(dialog.getByRole('alert')).toBeVisible()
  await dialog.getByRole('textbox', { name: 'Link URL' }).fill('https://example.com/a(b)')
  await dialog.getByRole('textbox', { name: 'Link text' }).fill('Updated link')
  await dialog.getByRole('button', { name: 'Save link' }).click()
  await expect(dialog).toHaveCount(0)
  await expect(visual.getByRole('link', { name: 'Updated link' })).toHaveAttribute('href', 'https://example.com/a(b)')
  await selectText(visual, 'One', 1, 1)
  await page.getByRole('button', { name: 'Table options', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Insert column right' }).click()
  await expect(visual.getByRole('columnheader')).toHaveCount(3)
  await page.getByRole('button', { name: 'Table options', exact: true }).click()
  await page.getByRole('menuitem', { name: 'Insert row below' }).click()
  await expect(visual.getByRole('row')).toHaveCount(3)
  await page.keyboard.press('Control+z')
  await expect(visual.getByRole('row')).toHaveCount(2)
  await selectText(visual, 'Two', 0, 3)
  await page.keyboard.press('Tab')
  await expect(visual.getByRole('row')).toHaveCount(3)
  await page.keyboard.type('New row')
  await expect(visual.getByRole('cell', { name: 'New row', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Markdown', exact: true }).click()
  const expected = 'Before bold and [Updated link](<https://example.com/a(b)>).\n\n| A | Header | B |\n| :--- | --- | ---: |\n| One |  | Two |\n| New row |  |  |\n\nAfter.'
  await expect(markdown).toHaveValue(expected)
  await page.keyboard.press('Control+s')
  await expect(page.getByTitle('Save changes')).toContainText('Saved on this device')
  await page.reload()
  await expect(markdown).toHaveValue(expected)
  expect(errors).toEqual([])
})

test('Visual mobile link dialog stays usable and table navigation preserves typing', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  const markdown = page.getByRole('textbox', { name: 'Markdown content', exact: true })
  await markdown.fill('A label.\n\n| A | B |\n| --- | --- |\n| One | Two |')
  await page.getByRole('button', { name: 'Visual', exact: true }).click()
  const visual = page.getByRole('textbox', { name: 'Visual content', exact: true })
  await selectText(visual, 'A label.', 2, 7)
  await page.getByRole('button', { name: 'Link', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Insert link', exact: true })
  await expect(dialog).toBeVisible()
  const bounds = await dialog.boundingBox()
  expect(bounds!.x).toBeGreaterThanOrEqual(0)
  expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(390)
  await dialog.getByRole('textbox', { name: 'Link URL' }).fill('https://example.com')
  await dialog.getByRole('button', { name: 'Save link' }).click()
  await selectText(visual, 'One')
  await page.keyboard.press('Tab')
  await page.keyboard.type('Changed')
  await expect(visual.getByRole('cell', { name: 'Changed', exact: true })).toBeVisible()
  await page.keyboard.press('Shift+Tab')
  await page.keyboard.type('First')
  await expect(visual.getByRole('cell', { name: 'First', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
